-- 1. TABELA DE CIDADAOS / REQUERENTES
CREATE TABLE tb_cidadao (
    id_cidadao         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_completo      VARCHAR2(150) NOT NULL,
    cpf                VARCHAR2(14)  NOT NULL,
    email              VARCHAR2(100),
    telefone           VARCHAR2(20),
    status             VARCHAR2(1)   DEFAULT 'A' NOT NULL, -- 'A'tivo, 'I'nativo
    data_cadastro      DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT uk_cidadao_cpf UNIQUE (cpf),
    CONSTRAINT ck_cidadao_status CHECK (status IN ('A', 'I'))
);

COMMENT ON TABLE tb_cidadao IS 'Cadastro de requerentes/cidadaos que abrem solicitacoes';
COMMENT ON COLUMN tb_cidadao.cpf IS 'CPF formatado ou numerico do cidadao com constraint de unicidade';

-- 2. TABELA DE CATEGORIAS DE DEMANDAS
CREATE TABLE tb_categoria_demanda (
    id_categoria       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo             VARCHAR2(30)  NOT NULL,
    descricao          VARCHAR2(100) NOT NULL,
    prazo_dias_sla     NUMBER(3)     DEFAULT 5 NOT NULL,
    ativo              VARCHAR2(1)   DEFAULT 'S' NOT NULL,
    CONSTRAINT uk_categoria_cod UNIQUE (codigo),
    CONSTRAINT ck_categoria_ativo CHECK (ativo IN ('S', 'N')),
    CONSTRAINT ck_categoria_sla CHECK (prazo_dias_sla > 0)
);

COMMENT ON TABLE tb_categoria_demanda IS 'Categorias das solicitacoes e definicao do prazo SLA padrao em dias';

-- 3. TABELA DE PROTOCOLOS DE ATENDIMENTO
CREATE TABLE tb_protocolo_atendimento (
    id_protocolo       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_protocolo   VARCHAR2(25)  NOT NULL,
    id_cidadao         NUMBER        NOT NULL,
    id_categoria       NUMBER        NOT NULL,
    assunto            VARCHAR2(200) NOT NULL,
    descricao          CLOB          NOT NULL,
    status             VARCHAR2(20)  DEFAULT 'ABERTO' NOT NULL,
    prioridade         VARCHAR2(10)  DEFAULT 'NORMAL' NOT NULL,
    data_abertura      DATE          DEFAULT SYSDATE NOT NULL,
    data_limite_sla    DATE          NOT NULL,
    data_conclusao     DATE,
    usuario_criacao    VARCHAR2(50)  DEFAULT USER NOT NULL,
    CONSTRAINT uk_protocolo_numero UNIQUE (numero_protocolo),
    CONSTRAINT fk_prot_cidadao FOREIGN KEY (id_cidadao) 
        REFERENCES tb_cidadao (id_cidadao),
    CONSTRAINT fk_prot_categoria FOREIGN KEY (id_categoria) 
        REFERENCES tb_categoria_demanda (id_categoria),
    CONSTRAINT ck_prot_status CHECK (status IN ('ABERTO', 'EM_ANDAMENTO', 'PENDENTE', 'CONCLUIDO', 'CANCELADO')),
    CONSTRAINT ck_prot_prioridade CHECK (prioridade IN ('BAIXA', 'NORMAL', 'ALTA', 'URGENTE'))
);

COMMENT ON TABLE tb_protocolo_atendimento IS 'Registro central de protocolos e acompanhamento de SLA';

-- 4. TABELA DE ANDAMENTOS / DESPACHOS
CREATE TABLE tb_andamento_processual (
    id_andamento       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_protocolo       NUMBER        NOT NULL,
    data_registro      DATE          DEFAULT SYSDATE NOT NULL,
    usuario_registro   VARCHAR2(50)  DEFAULT USER NOT NULL,
    status_anterior    VARCHAR2(20),
    status_novo        VARCHAR2(20)  NOT NULL,
    despacho_texto     CLOB          NOT NULL,
    CONSTRAINT fk_andam_protocolo FOREIGN KEY (id_protocolo) 
        REFERENCES tb_protocolo_atendimento (id_protocolo) ON DELETE CASCADE
);

COMMENT ON TABLE tb_andamento_processual IS 'Historico de tramitacao e despachos de cada protocolo';

-- 5. TABELA DE AUDITORIA TRANSACIONAL
CREATE TABLE tb_log_auditoria (
    id_log             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_tabela        VARCHAR2(50)  NOT NULL,
    operacao           VARCHAR2(10)  NOT NULL, -- 'INSERT', 'UPDATE', 'DELETE'
    id_registro        NUMBER        NOT NULL,
    usuario_sessao     VARCHAR2(50)  NOT NULL,
    data_evento        TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    payload_antigo     CLOB,
    payload_novo       CLOB,
    ip_origem          VARCHAR2(45)
);

COMMENT ON TABLE tb_log_auditoria IS 'Trilha de auditoria para registros sensiveis populada via triggers/packages autonomas';
